// Patch set model - the app's input.
//
// The patch set is generated on the PC from the lab's own CA (tools/app.mjs) and
// embedded in the XAP, so the phone can only ever be patched with the certificate
// the lab is actually serving. Nothing here is hardcoded in the app.

using System.Collections.Generic;
using System.Runtime.Serialization;

namespace Store_Patcher.Models
{
    [DataContract]
    public sealed class PatchSet
    {
        [DataMember(Name = "schemaVersion")]
        public int SchemaVersion { get; set; }

        [DataMember(Name = "generatedAt")]
        public string GeneratedAt { get; set; }

        [DataMember(Name = "lab")]
        public LabInfo Lab { get; set; }

        [DataMember(Name = "patches")]
        public List<PatchDefinition> Patches { get; set; }
    }

    [DataContract]
    public sealed class LabInfo
    {
        /// <summary>Address of the lab on the local network, for display and for future url-map patches.</summary>
        [DataMember(Name = "advertiseIp")]
        public string AdvertiseIp { get; set; }
    }

    /// <summary>
    /// One patch. Unknown <see cref="Kind"/> values are skipped rather than failing
    /// the run, so a patch set generated by a newer lab still applies what this app
    /// build understands.
    /// </summary>
    [DataContract]
    public sealed class PatchDefinition
    {
        [DataMember(Name = "id")]
        public string Id { get; set; }

        /// <summary>Patch kind: "cert-root" today; "url-map" and "reg-binary" are reserved.</summary>
        [DataMember(Name = "kind")]
        public string Kind { get; set; }

        [DataMember(Name = "hive")]
        public string Hive { get; set; }

        [DataMember(Name = "store")]
        public string Store { get; set; }

        /// <summary>SHA-1 thumbprint of the certificate, uppercase hex - the registry key name.</summary>
        [DataMember(Name = "thumbprint")]
        public string Thumbprint { get; set; }

        /// <summary>
        /// The exact REG_BINARY "Blob" bytes Windows itself writes for this certificate.
        /// The desktop side proves the layout byte-for-byte (`npm run verify-rootreg`);
        /// the app writes those bytes instead of re-implementing the format.
        /// </summary>
        [DataMember(Name = "blobBase64")]
        public string BlobBase64 { get; set; }

        /// <summary>The certificate itself, DER, base64 - used by the certificate store API route.</summary>
        [DataMember(Name = "derBase64")]
        public string DerBase64 { get; set; }

        [DataMember(Name = "requiresReboot")]
        public bool RequiresReboot { get; set; }

        [DataMember(Name = "description")]
        public string Description { get; set; }
    }
}
