// Loads the patch set that was embedded in the XAP at build time.
//
// A build without a patch set must not silently do nothing: the caller gets an
// exception with the exact command that fixes it, and the screen shows it.

using System;
using System.Collections.Generic;
using System.IO;
using System.Runtime.Serialization.Json;
using System.Windows;            // Application
using System.Windows.Resources;  // StreamResourceInfo lives here, not in System.Windows

using Store_Patcher.Models;

namespace Store_Patcher.Services
{
    public static class PatchSetLoader
    {
        /// <summary>Name of the Content item generated by tools/app.mjs and packed into the XAP.</summary>
        public const string ResourceName = "patches.json";

        public static PatchSet Load()
        {
            StreamResourceInfo info = Application.GetResourceStream(new Uri(ResourceName, UriKind.Relative));
            if (info == null)
            {
                throw new FileNotFoundException(
                    "patches.json is not present in this build. Generate it and rebuild: node tools/app.mjs build",
                    ResourceName);
            }

            using (Stream stream = info.Stream)
            {
                DataContractJsonSerializer serializer = new DataContractJsonSerializer(typeof(PatchSet));
                PatchSet set = (PatchSet)serializer.ReadObject(stream);

                if (set == null) throw new InvalidDataException("patches.json could not be parsed");

                if (set.Patches == null) set.Patches = new List<PatchDefinition>();
                if (set.Lab == null) set.Lab = new LabInfo();
                if (set.App == null) set.App = new AppInfo();

                return set;
            }
        }
    }
}
